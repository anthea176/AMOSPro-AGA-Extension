; AGA_NATIVE_MIN_CPU: MC68020
; P2a pair Chip resolver, source: tools/m19_p2a_pair_chip_resolve_emit.py.
; BOBS+$08BB6..+$08E20, 618 instruction bytes, 120-byte atomic output.
; D0/D1 Bob IDs; A1 output; A4 checked callback; A6 source image resolver.
p2a_pair_chip_resolve_entry:
    movem.l d0-d2/d4-d7/a0-a2/a4-a6,-(a7)
    lea -256(a7),a7
    movea.l a7,a2
    move.l d0,(a2)
    move.l d1,4(a2)
    move.l a1,8(a2)
    move.l a4,12(a2)
    move.l a6,16(a2)
    move.l #0,20(a2)
    move.l 12(a2),d0
    tst.l d0
    beq.w p2a_pair_chip_return
    andi.l #1,d0
    bne.w p2a_pair_chip_return
    move.l 16(a2),d0
    tst.l d0
    beq.w p2a_pair_chip_return
    andi.l #1,d0
    bne.w p2a_pair_chip_return
    move.l 8(a2),d0
    tst.l d0
    beq.w p2a_pair_chip_return
    andi.l #1,d0
    bne.w p2a_pair_chip_return
    move.l 8(a2),d0
    movea.l d0,a1
    movea.l $0004.w,a6
    jsr -534(a6)
    tst.l d0
    beq.w p2a_pair_chip_return
    move.l 8(a2),d0
    addi.l #119,d0
    bcs.w p2a_pair_chip_return
    movea.l d0,a1
    movea.l $0004.w,a6
    jsr -534(a6)
    tst.l d0
    beq.w p2a_pair_chip_return
    ; Snapshot both source checked Bob records before Chip image accesses.
    move.l (a2),d0
    move.l 4(a2),d1
    move.l a2,d4
    addi.l #64,d4
    movea.l d4,a1
    movea.l 12(a2),a4
    bsr.w p2a_pair_checked_read_entry
    tst.l d3
    beq.w p2a_pair_chip_return
    move.l 64(a2),d3
    move.l 68(a2),d0
    move.l a2,d4
    addi.l #120,d4
    movea.l d4,a1
    movea.l 16(a2),a6
    jsr (a6)
    tst.l d3
    beq.w p2a_pair_chip_return
    move.l 88(a2),d3
    move.l 92(a2),d0
    move.l a2,d4
    addi.l #156,d4
    movea.l d4,a1
    movea.l 16(a2),a6
    jsr (a6)
    tst.l d3
    beq.w p2a_pair_chip_return
    ; Recheck the source Bob identity after both resolver callbacks.
    move.l (a2),d0
    move.l 4(a2),d1
    move.l a2,d4
    addi.l #200,d4
    movea.l d4,a1
    movea.l 12(a2),a4
    bsr.w p2a_pair_checked_read_entry
    tst.l d3
    beq.w p2a_pair_chip_return
    move.l 64(a2),d4
    cmp.l 200(a2),d4
    bne.w p2a_pair_chip_return
    move.l 68(a2),d4
    cmp.l 204(a2),d4
    bne.w p2a_pair_chip_return
    move.l 72(a2),d4
    cmp.l 208(a2),d4
    bne.w p2a_pair_chip_return
    move.l 76(a2),d4
    cmp.l 212(a2),d4
    bne.w p2a_pair_chip_return
    move.l 80(a2),d4
    cmp.l 216(a2),d4
    bne.w p2a_pair_chip_return
    move.l 84(a2),d4
    cmp.l 220(a2),d4
    bne.w p2a_pair_chip_return
    move.l 88(a2),d4
    cmp.l 224(a2),d4
    bne.w p2a_pair_chip_return
    move.l 92(a2),d4
    cmp.l 228(a2),d4
    bne.w p2a_pair_chip_return
    move.l 96(a2),d4
    cmp.l 232(a2),d4
    bne.w p2a_pair_chip_return
    move.l 100(a2),d4
    cmp.l 236(a2),d4
    bne.w p2a_pair_chip_return
    move.l 104(a2),d4
    cmp.l 240(a2),d4
    bne.w p2a_pair_chip_return
    move.l 108(a2),d4
    cmp.l 244(a2),d4
    bne.w p2a_pair_chip_return
    ; Commit only after both source identity checks agree.
    movea.l 8(a2),a0
    move.l 64(a2),d4
    move.l d4,(a0)+
    move.l 68(a2),d4
    move.l d4,(a0)+
    move.l 72(a2),d4
    move.l d4,(a0)+
    move.l 76(a2),d4
    move.l d4,(a0)+
    move.l 80(a2),d4
    move.l d4,(a0)+
    move.l 84(a2),d4
    move.l d4,(a0)+
    move.l 120(a2),d4
    move.l d4,(a0)+
    move.l 124(a2),d4
    move.l d4,(a0)+
