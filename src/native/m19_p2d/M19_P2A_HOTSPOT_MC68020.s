; AGA_NATIVE_MIN_CPU: MC68020
; P2a signed hotspot reader from tools/m19_p2a_pair_hotspot020_emit.py.
; Source-backed BOBS+$08E20..+$0918A, exactly 874 executable bytes.
; Validates original AGBO identities/width/stride/generation twice.
; Pair record A0=120B, output A1=8B, explicit lookup callback A4.
p2a_pair_hotspot_entry:
    movem.l d0-d2/d4-d7/a0-a2/a4-a6,-(a7)
    lea -192(a7),a7
    movea.l a7,a2
    move.l a0,(a2)
    move.l a1,4(a2)
    move.l a4,8(a2)
    move.l #0,12(a2)
    move.l (a2),d4
    tst.l d4
    beq.w p2a_hot_refuse
    andi.l #1,d4
    bne.w p2a_hot_refuse
    move.l 4(a2),d4
    tst.l d4
    beq.w p2a_hot_refuse
    andi.l #1,d4
    bne.w p2a_hot_refuse
    move.l 8(a2),d4
    tst.l d4
    beq.w p2a_hot_refuse
    andi.l #1,d4
    bne.w p2a_hot_refuse
    ; Lookup source bank for Bob A.
    movea.l (a2),a0
    move.l (a0),d3
    move.l a2,d4
    addi.l #48,d4
    movea.l d4,a1
    movea.l 8(a2),a4
    jsr (a4)
    tst.l d3
    beq.w p2a_hot_refuse
    movea.l (a2),a1
    move.l 4(a1),d1
    move.l d1,20(a2)
    cmpi.l #1,d1
    bcs.w p2a_hot_refuse
    cmpi.l #4096,d1
    bhi.w p2a_hot_refuse
    move.l 48(a2),d4
    tst.l d4
    beq.w p2a_hot_refuse
    movea.l d4,a0
    move.l #0,d4
    move.w 8(a0),d4
    cmpi.l #1,d4
    bcs.w p2a_hot_refuse
    cmpi.l #4096,d4
    bhi.w p2a_hot_refuse
    move.l d4,16(a2)
    move.l a0,d4
    addi.l #32,d4
    bcs.w p2a_hot_refuse
    movea.l d4,a0
p2a_h0_scan:
    move.l #0,d4
    move.w (a0),d4
    move.l 20(a2),d5
    cmp.l d5,d4
    beq.w p2a_h0_found
    move.l a0,d4
    addi.l #40,d4
    bcs.w p2a_hot_refuse
    movea.l d4,a0
    move.l 16(a2),d4
    subq.l #1,d4
    move.l d4,16(a2)
    bne.w p2a_h0_scan
    bra.w p2a_hot_refuse
p2a_h0_found:
    movea.l (a2),a1
    move.l #0,d4
    move.w 2(a0),d4
    cmp.l 32(a1),d4
    bne.w p2a_hot_refuse
    move.l #0,d4
    move.w 4(a0),d4
    cmp.l 36(a1),d4
    bne.w p2a_hot_refuse
    move.l #0,d4
    move.w 6(a0),d4
    cmp.l 44(a1),d4
    bne.w p2a_hot_refuse
    move.l #0,d4
    move.w 8(a0),d4
    cmp.l 40(a1),d4
    bne.w p2a_hot_refuse
    move.w 28(a0),d4
    move.w d4,144(a2)
    move.w 30(a0),d4
    move.w d4,146(a2)
    ; Lookup source bank for Bob B.
    movea.l (a2),a0
    move.l 60(a0),d3
    move.l a2,d4
    addi.l #80,d4
    movea.l d4,a1
    movea.l 8(a2),a4
    jsr (a4)
    tst.l d3
    beq.w p2a_hot_refuse
    movea.l (a2),a1
    move.l 64(a1),d1
    move.l d1,20(a2)
    cmpi.l #1,d1
    bcs.w p2a_hot_refuse
    cmpi.l #4096,d1
    bhi.w p2a_hot_refuse
    move.l 80(a2),d4
    tst.l d4
    beq.w p2a_hot_refuse
    movea.l d4,a0
    move.l #0,d4
    move.w 8(a0),d4
    cmpi.l #1,d4
    bcs.w p2a_hot_refuse
    cmpi.l #4096,d4
    bhi.w p2a_hot_refuse
    move.l d4,16(a2)
    move.l a0,d4
    addi.l #32,d4
    bcs.w p2a_hot_refuse
    movea.l d4,a0
p2a_h1_scan:
    move.l #0,d4
    move.w (a0),d4
    move.l 20(a2),d5
    cmp.l d5,d4
    beq.w p2a_h1_found
    move.l a0,d4
    addi.l #40,d4
    bcs.w p2a_hot_refuse
    movea.l d4,a0
    move.l 16(a2),d4
    subq.l #1,d4
    move.l d4,16(a2)
    bne.w p2a_h1_scan
    bra.w p2a_hot_refuse
p2a_h1_found:
    movea.l (a2),a1
    move.l #0,d4
    move.w 2(a0),d4
    cmp.l 92(a1),d4
    bne.w p2a_hot_refuse
    move.l #0,d4
    move.w 4(a0),d4
    cmp.l 96(a1),d4
    bne.w p2a_hot_refuse
    move.l #0,d4
    move.w 6(a0),d4
    cmp.l 104(a1),d4
    bne.w p2a_hot_refuse
    move.l #0,d4
    move.w 8(a0),d4
    cmp.l 100(a1),d4
    bne.w p2a_hot_refuse
    move.w 28(a0),d4
    move.w d4,148(a2)
    move.w 30(a0),d4
    move.w d4,150(a2)
    ; Lookup source bank for Bob A.
    movea.l (a2),a0
    move.l (a0),d3
    move.l a2,d4
    addi.l #112,d4
    movea.l d4,a1
    movea.l 8(a2),a4
    jsr (a4)
    tst.l d3
    beq.w p2a_hot_refuse
    move.l 112(a2),d4
    cmp.l 48(a2),d4
    bne.w p2a_hot_refuse
    move.l 116(a2),d4
    cmp.l 52(a2),d4
    bne.w p2a_hot_refuse
    move.l 120(a2),d4
    cmp.l 56(a2),d4
    bne.w p2a_hot_refuse
    move.l 124(a2),d4
    cmp.l 60(a2),d4
    bne.w p2a_hot_refuse
    move.l 128(a2),d4
    cmp.l 64(a2),d4
    bne.w p2a_hot_refuse
    move.l 132(a2),d4
    cmp.l 68(a2),d4
    bne.w p2a_hot_refuse
    move.l 136(a2),d4
    cmp.l 72(a2),d4
    bne.w p2a_hot_refuse
    ; Lookup source bank for Bob B.
    movea.l (a2),a0
    move.l 60(a0),d3
    move.l a2,d4
    addi.l #112,d4
    movea.l d4,a1
    movea.l 8(a2),a4
    jsr (a4)
    tst.l d3
    beq.w p2a_hot_refuse
    move.l 112(a2),d4
    cmp.l 80(a2),d4
    bne.w p2a_hot_refuse
    move.l 116(a2),d4
    cmp.l 84(a2),d4
    bne.w p2a_hot_refuse
    move.l 120(a2),d4
    cmp.l 88(a2),d4
    bne.w p2a_hot_refuse
    move.l 124(a2),d4
    cmp.l 92(a2),d4
    bne.w p2a_hot_refuse
    move.l 128(a2),d4
    cmp.l 96(a2),d4
    bne.w p2a_hot_refuse
    move.l 132(a2),d4
    cmp.l 100(a2),d4
    bne.w p2a_hot_refuse
    move.l 136(a2),d4
    cmp.l 104(a2),d4
    bne.w p2a_hot_refuse
    ; Both directory lookups agreed; publish 4 signed hotspot WORDs.
    movea.l 4(a2),a0
    move.w 144(a2),d4
    move.w d4,(a0)+
    move.w 146(a2),d4
    move.w d4,(a0)+
    move.w 148(a2),d4
    move.w d4,(a0)+
    move.w 150(a2),d4
    move.w d4,(a0)+
    move.l #1,12(a2)
p2a_hot_refuse:
    move.l 12(a2),d3
    lea 192(a7),a7
    movem.l (a7)+,d0-d2/d4-d7/a0-a2/a4-a6
    moveq #0,d2
    rts
