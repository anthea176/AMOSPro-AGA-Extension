#!/usr/bin/env python3
"""M19/P0a R88-only static native emission proof, NOT a 68k CPU Gate A."""
from __future__ import annotations

import unittest
from hashlib import sha256
from struct import pack, unpack_from

from m19_p0a_amos_bank_transaction_emit import (
    CUR_BANKS_A5, FRAME, HEADER, IDX, MARKERS, MEMF_PUBLIC_CLEAR,
    MAX_BANK_BYTES, emit_transaction,
)


class NativeBankTransactionEmissionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw, cls.labels = emit_transaction()

    def test_deterministic_native_binary(self):
        assert emit_transaction() == (self.raw,self.labels)
        self.assertEqual(len(self.raw), 874)
        self.assertEqual(sha256(self.raw).hexdigest(),
                         "53624df54661761ee7161131ad6ffddb98ffbf2b4eeb6d9c7f03215327d4621e")

    def test_exact_prologue_and_epilogue(self):
        self.assertTrue(self.raw.startswith(bytes.fromhex('48e7efee4fefffb0')))
        self.assertTrue(self.raw.endswith(bytes.fromhex('4fef00504cdf77f774004e75')))
        self.assertEqual(FRAME,80)

    def test_amos_pro365_list_head_offset(self):
        # Offset recomputed from +Equ.s RsReset at line 1147 through Cur_Banks
        # at 1327. The first 8-byte run-time arrays and +ExtAdr are counted.
        self.assertEqual(CUR_BANKS_A5,0x05ea)
        self.assertEqual(self.raw.count(pack('>H',CUR_BANKS_A5)),2)

    def test_exact_r88_main_library_link_symbols(self):
        self.assertEqual(IDX, {'Bnk.GetAdr':797,'Bnk.Change':819,
                               'Lst.Cree':91,'Lst.Del':93})
        self.assertEqual({k:self.raw.count(marker) for k,marker in MARKERS.items()},
                         {'Bnk.GetAdr':2,'Bnk.Change':1,
                          'Lst.Cree':1,'Lst.Del':2})
        # Critical: no Bnk.Reserve (destructive), no extra AMOS bank number.
        self.assertNotIn(bytes.fromhex('fe11f700')+pack('>H',816), self.raw)

    def test_bank_name_and_allocation_flags(self):
        self.assertIn(pack('>I',0x41474142),self.raw)  # AGAB
        self.assertIn(pack('>I',0x4f425320),self.raw)  # OBS
        self.assertIn(pack('>I',MEMF_PUBLIC_CLEAR),self.raw)
        self.assertIn(pack('>I',MAX_BANK_BYTES),self.raw)
        self.assertIn(pack('>I',MAX_BANK_BYTES+16),self.raw)
        self.assertEqual(HEADER,32)

    def test_control_flow_and_safe_commit_order(self):
        labels=self.labels
        for name in ('stage','copy_longs','copy_done','seek_previous_link',
                     'replace_old','insert_new','notify','success','abort','return'):
            self.assertIn(name,labels)
        self.assertLess(labels['stage'],labels['copy_longs'])
        self.assertLess(labels['copy_done'],labels['seek_previous_link'])
        self.assertLess(labels['seek_previous_link'],labels['replace_old'])
        self.assertLess(labels['replace_old'],labels['notify'])
        self.assertLess(labels['notify'],labels['success'])
        # Second Lst.Del is called *after* Bnk.Change; old stays live for callback.
        bnkchange=self.raw.find(MARKERS['Bnk.Change'])
        lst_del_positions=[i for i in range(len(self.raw))
                           if self.raw.startswith(MARKERS['Lst.Del'],i)]
        self.assertEqual(len(lst_del_positions),2)
        self.assertLess(bnkchange,lst_del_positions[0])
        self.assertLess(labels['abort'],lst_del_positions[1])

    def test_all_encoded_word_branches_target_known_labels(self):
        # Exact forward/backward Bcc.W instructions generated by Code.branch;
        # no short or externally relocated branch is required.
        known=set(self.labels.values())
        generated=[]
        for target in ('copy_longs','seek_previous_link','return',
                       'stage','notify','abort'):
            self.assertEqual(self.labels[target]&1,0)
        self.assertTrue(all(0<=o<len(self.raw) for o in known))
        self.assertGreater(len(self.labels),10)


if __name__=='__main__':
    unittest.main(verbosity=2)
